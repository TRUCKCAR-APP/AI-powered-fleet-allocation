CREATE TABLE IF NOT EXISTS allocation_decisions (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    load_id                    BIGINT        NOT NULL,
    selected_driver_id         VARCHAR(255),
    selected_driver_name       VARCHAR(255),
    selected_vehicle_plate     VARCHAR(255),
    matching_score             DOUBLE PRECISION,
    deadhead_distance_km       DOUBLE PRECISION,
    evaluated_candidates_count INTEGER,
    status                     VARCHAR(255)  NOT NULL,
    reason_details             VARCHAR(1000),
    executed_at                TIMESTAMP(6)  NOT NULL,
    CONSTRAINT allocation_decisions_status_check CHECK (status IN
        ('SUCCESSFUL', 'NO_DRIVERS_AVAILABLE', 'REJECTED', 'DEGRADED_USING_CACHE', 'RECOMMENDATION_PENDING',
         'ASSIGNMENT_CONFLICT', 'ASSIGNMENT_FAILED'))
);

CREATE INDEX IF NOT EXISTS idx_decision_load ON allocation_decisions (load_id);
CREATE INDEX IF NOT EXISTS idx_decision_driver ON allocation_decisions (selected_driver_id);
